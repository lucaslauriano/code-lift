// Bundles the Web Worker entry into a single self-contained script and emits it as a TS module
// exporting the source as a string. The client turns that string into a Blob URL, which is why the
// consuming app never needs worker-specific bundler configuration.
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const here = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(here, '..');
const outFile = resolve(packageRoot, 'src/generated/worker-source.ts');

const result = await build({
  entryPoints: [resolve(packageRoot, 'src/worker/entry.ts')],
  bundle: true,
  write: false,
  format: 'iife',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  legalComments: 'none',
  logLevel: 'warning',
});

const [output] = result.outputFiles;
if (!output) throw new Error('esbuild produced no output for the worker bundle');

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  `// GENERATED by scripts/build-worker.mjs — do not edit.\n` +
    `export const WORKER_SOURCE = ${JSON.stringify(output.text)};\n`,
  'utf8',
);

const kb = (output.text.length / 1024).toFixed(1);
process.stdout.write(`worker bundle: ${kb} kB\n`);
